#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const ownerId = readArg('--owner-id') || 'owner-import';
const ownerEmail = readArg('--owner-email');
const source = readArg('--source') || 'json-import';
const now = nowIso();
const ownerRef = ownerEmail
  ? `(SELECT id FROM users WHERE email = ${sql(ownerEmail)} LIMIT 1)`
  : sql(ownerId);

const statements = [];
statements.push(`-- Generated by scripts/import-json-to-d1.js at ${now}`);
statements.push('-- Re-runnable import: existing rows are kept with INSERT OR IGNORE.');
statements.push('BEGIN TRANSACTION;');

if (!ownerEmail) {
  statements.push(`
INSERT OR IGNORE INTO users (
  id, google_sub, email, email_verified, name, avatar_url, role, created_at, updated_at, last_login_at
) VALUES (
  ${sql(ownerId)}, ${sql(`import:${ownerId}`)}, ${sql('import-owner@example.local')}, 1,
  ${sql('Imported Owner')}, NULL, 'owner', ${sql(now)}, ${sql(now)}, ${sql(now)}
);
`.trim());
} else {
  statements.push(`-- Owner is resolved by email: ${ownerEmail}`);
}

importDailyRecords();
importProjects();
importFollowups();
importContentItems();
importDomainSettings();
importPeriodReviews();

statements.push('COMMIT;');
process.stdout.write(`${statements.join('\n\n')}\n`);

function importDailyRecords() {
  const dailyDir = path.join(root, 'data/records/daily');
  const files = listJsonFiles(dailyDir, /^\d{4}-\d{2}-\d{2}\.json$/);

  for (const file of files) {
    const daily = readJson(path.join(dailyDir, file));
    const date = cleanDate(daily?.date) || file.replace('.json', '');
    if (!date) continue;

    for (const record of daily.records || []) {
      const createdAt = record.createdAt || `${date}T00:00:00+08:00`;
      const id = record.id || `record-${date}-${stableSlug(record.raw || record.content || record.summary || createdAt)}`;
      statements.push(`
INSERT OR IGNORE INTO records (
  id, owner_id, date, created_at, updated_at, domain, type, raw_content, summary,
  visibility, mood, energy, projects_json, tags_json, next_actions_json, source, legacy_id
) VALUES (
  ${sql(id)},
  ${ownerRef},
  ${sql(date)},
  ${sql(createdAt)},
  ${sql(record.updatedAt || createdAt)},
  ${sql(normalizeDomain(record.domain))},
  ${sql(record.type || 'thought')},
  ${sql(record.raw || record.content || record.summary || '')},
  ${sql(record.summary || null)},
  ${sql(record.visibility || 'private')},
  ${sql(record.mood || null)},
  ${record.energy == null ? 'NULL' : Number(record.energy)},
  ${sql(JSON.stringify(arrayOrEmpty(record.projects)))},
  ${sql(JSON.stringify(arrayOrEmpty(record.tags)))},
  ${sql(JSON.stringify(arrayOrEmpty(record.nextActions)))},
  ${sql(record.source || source)},
  ${sql(id)}
);
`.trim());
    }

    if (daily.dailyReview) {
      const review = daily.dailyReview;
      statements.push(`
INSERT OR IGNORE INTO daily_reviews (
  id, owner_id, date, most_important_thing, wins_json, blockers_json, reflection,
  tomorrow_first_step, mood, energy, created_at, updated_at
) VALUES (
  ${sql(`daily-review-${date}`)},
  ${ownerRef},
  ${sql(date)},
  ${sql(review.mostImportantThing || null)},
  ${sql(JSON.stringify(arrayOrEmpty(review.wins)))},
  ${sql(JSON.stringify(arrayOrEmpty(review.blockers)))},
  ${sql(review.reflection || null)},
  ${sql(review.tomorrowFirstStep || null)},
  ${sql(review.mood || null)},
  ${review.energy == null ? 'NULL' : Number(review.energy)},
  ${sql(review.createdAt || now)},
  ${sql(review.updatedAt || now)}
);
`.trim());
    }
  }
}

function importProjects() {
  const manifest = readJson(path.join(root, 'data/summaries/projects/manifest.json'));
  for (const project of manifest?.projects || []) {
    if (!project.name || !project.slug) continue;

    const detail = readJson(path.join(root, `data/summaries/projects/${project.slug}.json`)) || {};
    const openFollowup = firstText(detail.openFollowUps) || firstText(project.openFollowUps);
    const createdAt = dateToIso(project.firstSeen || detail.firstSeen, 'start') || now;
    const updatedAt = dateToIso(project.lastUpdated || detail.lastUpdated, 'end') || createdAt;

    statements.push(`
INSERT OR IGNORE INTO projects (
  id, owner_id, slug, name, summary, status, current_focus, next_action, created_at, updated_at
) VALUES (
  ${sql(`legacy-project-${project.slug}`)},
  ${ownerRef},
  ${sql(project.slug)},
  ${sql(project.name)},
  ${sql(project.summary || detail.summary || null)},
  ${sql(project.status || detail.status || 'active')},
  ${sql(project.summary || detail.summary || null)},
  ${sql(openFollowup || null)},
  ${sql(createdAt)},
  ${sql(updatedAt)}
);
`.trim());
  }
}

function importFollowups() {
  const all = readJson(path.join(root, 'data/summaries/followups/all.json'));
  const open = readJson(path.join(root, 'data/summaries/followups/open.json'));
  const followups = dedupeById([...(all?.followups || []), ...(open?.followups || [])]);

  for (const item of followups) {
    const text = cleanText(item.text);
    if (!text) continue;

    const createdAt = dateToIso(item.createdAt || item.sourceDate, 'start') || now;
    const closedAt = item.closedAt ? dateToIso(item.closedAt, 'end') : null;
    const updatedAt = closedAt || createdAt;

    statements.push(`
INSERT OR IGNORE INTO followups (
  id, owner_id, text, domain, project, status, source_record_id, due_date,
  created_at, updated_at, closed_at
) VALUES (
  ${sql(item.id || `legacy-followup-${stableSlug(`${text}-${createdAt}`)}`)},
  ${ownerRef},
  ${sql(text)},
  ${sql(normalizeDomain(item.domain))},
  ${sql(cleanText(item.project))},
  ${sql(normalizeFollowupStatus(item.status))},
  ${sql(cleanText(item.sourceRecordId))},
  NULL,
  ${sql(createdAt)},
  ${sql(updatedAt)},
  ${sql(closedAt)}
);
`.trim());
  }
}

function importContentItems() {
  const data = readJson(path.join(root, 'data/summaries/content/seeds.json'));
  for (const item of data?.seeds || []) {
    const title = cleanText(item.title);
    if (!title) continue;

    const createdAt = dateToIso(item.sourceDate, 'start') || now;
    statements.push(`
INSERT OR IGNORE INTO content_items (
  id, owner_id, title, source_domain, status, angle, outline_json, tags_json,
  next_action, created_at, updated_at
) VALUES (
  ${sql(item.id || `legacy-content-${stableSlug(title)}`)},
  ${ownerRef},
  ${sql(title)},
  ${sql(normalizeDomain(item.sourceDomain))},
  ${sql(normalizeContentStatus(item.status))},
  ${sql(cleanText(item.angle))},
  ${sql(JSON.stringify(arrayOrEmpty(item.outline)))},
  ${sql(JSON.stringify(arrayOrEmpty(item.tags)))},
  ${sql(cleanText(item.nextAction))},
  ${sql(createdAt)},
  ${sql(createdAt)}
);
`.trim());
  }
}

function importDomainSettings() {
  const manifest = readJson(path.join(root, 'data/summaries/domains/manifest.json'));
  const overview = readJson(path.join(root, 'data/summaries/domains/overview.json'));
  const domainIds = new Set([
    ...((manifest?.domains || []).map(item => item.id || item)),
    ...((overview?.domains || []).map(item => item.id))
  ].filter(Boolean));

  for (const domainId of domainIds) {
    const normalizedDomain = normalizeDomain(domainId);
    if (!normalizedDomain) continue;

    const detail = readJson(path.join(root, `data/summaries/domains/${domainId}.json`)) || {};
    const overviewItem = (overview?.domains || []).find(item => item.id === domainId) || {};
    const currentFocus = cleanText(detail.currentFocus || overviewItem.currentFocus);
    const nextAction = cleanText(detail.nextAction || overviewItem.nextAction);
    if (!currentFocus && !nextAction) continue;

    statements.push(`
INSERT OR IGNORE INTO domain_settings (
  owner_id, domain, current_focus, next_action, updated_at
) VALUES (
  ${ownerRef},
  ${sql(normalizedDomain)},
  ${sql(currentFocus)},
  ${sql(nextAction)},
  ${sql(overview?.generatedAt || now)}
);
`.trim());
  }
}

function importPeriodReviews() {
  importWeeklyPeriodReviews();
  importMonthlyPeriodReviews();
  importYearlyPeriodReviews();
}

function importWeeklyPeriodReviews() {
  const dir = path.join(root, 'data/summaries/insights/weekly');
  for (const file of listJsonFiles(dir, /^\d{4}-W\d{2}\.json$/)) {
    const insight = readJson(path.join(dir, file));
    const key = insight?.week || file.replace('.json', '');
    if (!key) continue;
    statements.push(periodReviewInsert({
      type: 'weekly',
      key,
      theme: insight.theme || null,
      summary: insight.summary || null,
      wins: insight.wins || [],
      blockers: insight.blockers || [],
      nextActions: insight.nextWeekFocus || insight.openFollowUps || []
    }));
  }
}

function importMonthlyPeriodReviews() {
  const dir = path.join(root, 'data/summaries/monthly');
  for (const file of listJsonFiles(dir, /^\d{4}-\d{2}\.json$/)) {
    const month = readJson(path.join(dir, file));
    const key = file.replace('.json', '');
    if (!month) continue;
    statements.push(periodReviewInsert({
      type: 'monthly',
      key,
      theme: `${month.monthName || key}策略复盘`,
      summary: month.modeSummary || null,
      wins: month.topProjects || [],
      blockers: month.repeatedBlockers || [],
      nextActions: month.nextMonthStrategy || []
    }));
  }
}

function importYearlyPeriodReviews() {
  const dir = path.join(root, 'data/summaries/yearly');
  for (const file of listJsonFiles(dir, /^\d{4}\.json$/)) {
    const year = readJson(path.join(dir, file));
    const key = file.replace('.json', '');
    if (!year) continue;
    statements.push(periodReviewInsert({
      type: 'yearly',
      key,
      theme: `${key} 年度复盘`,
      summary: `${key} 年累计 ${year.totalAchievements || 0} 条成就，推进 ${year.totalProjects || 0} 个项目。`,
      wins: year.topTags || [],
      blockers: [],
      nextActions: []
    }));
  }
}

function periodReviewInsert({ type, key, theme, summary, wins, blockers, nextActions }) {
  return `
INSERT OR IGNORE INTO period_reviews (
  id, owner_id, period_type, period_key, theme, summary, wins_json, blockers_json,
  next_actions_json, status, created_at, updated_at
) VALUES (
  ${sql(`legacy-period-${type}-${key}`)},
  ${ownerRef},
  ${sql(type)},
  ${sql(key)},
  ${sql(theme)},
  ${sql(summary)},
  ${sql(JSON.stringify(arrayOrEmpty(wins)))},
  ${sql(JSON.stringify(arrayOrEmpty(blockers)))},
  ${sql(JSON.stringify(arrayOrEmpty(nextActions)))},
  'confirmed',
  ${sql(now)},
  ${sql(now)}
);
`.trim();
}

function listJsonFiles(dir, pattern) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(name => pattern.test(name)).sort();
}

function readJson(filePath) {
  if (!fs.existsSync(filePath)) return null;
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function readArg(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return null;
  return process.argv[index + 1] || null;
}

function sql(value) {
  if (value == null || value === '') return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function nowIso() {
  return new Date().toISOString();
}

function cleanText(value) {
  const text = String(value || '').trim();
  return text || null;
}

function cleanDate(value) {
  const text = cleanText(value);
  return /^\d{4}-\d{2}-\d{2}$/.test(text || '') ? text : null;
}

function dateToIso(value, mode = 'start') {
  const text = cleanDate(value);
  if (!text) return null;
  return `${text}T${mode === 'end' ? '23:59:59' : '00:00:00'}+08:00`;
}

function normalizeDomain(domain) {
  const allowed = new Set(['work', 'side_business', 'life', 'content']);
  return allowed.has(domain) ? domain : null;
}

function normalizeFollowupStatus(status) {
  const allowed = new Set(['open', 'deferred', 'closed', 'dropped']);
  return allowed.has(status) ? status : 'open';
}

function normalizeContentStatus(status) {
  const allowed = new Set(['idea', 'outline', 'drafting', 'published', 'dropped']);
  return allowed.has(status) ? status : 'idea';
}

function arrayOrEmpty(value) {
  if (!value) return [];
  return Array.isArray(value) ? value.filter(item => item != null && String(item).trim()) : [String(value)];
}

function firstText(value) {
  const list = arrayOrEmpty(value);
  const first = list[0];
  if (!first) return null;
  if (typeof first === 'string') return first;
  return first.text || first.title || null;
}

function dedupeById(items) {
  const seen = new Set();
  const result = [];
  for (const item of items) {
    const key = item.id || `${item.text}-${item.createdAt || item.sourceDate || ''}`;
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(item);
  }
  return result;
}

function stableSlug(value) {
  const text = String(value || 'item')
    .toLowerCase()
    .replace(/['"]/g, '')
    .replace(/[^a-z0-9\u4e00-\u9fa5]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return text.slice(0, 48) || 'item';
}
